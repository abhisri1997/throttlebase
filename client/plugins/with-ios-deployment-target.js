const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

/**
 * Raises every CocoaPods target to the app's own iOS deployment target.
 *
 * Xcode 27 refuses to build anything below iOS 15.0. CocoaPods gives each
 * generated resource-bundle target the deployment target declared in its own
 * podspec, and several vendored pods (GoogleSignIn, GoogleMaps, PromisesObjC,
 * RNSVG, AsyncStorage) still declare 9.0-14.0. Those targets are not covered
 * by `platform :ios` in the Podfile, so the build fails during project
 * generation, before a single source file is compiled.
 *
 * This lives in a plugin rather than in ios/Podfile because ios/ is
 * gitignored and regenerated by `expo prebuild`, which would discard a
 * hand-edit.
 *
 * Remove this once the upstream pods raise their own minimums.
 */

const MARKER = '# @generated throttlebase-ios-deployment-target';

const buildPatch = (minimum) => `
    ${MARKER}
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |config|
        current = config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'].to_f
        if current > 0 && current < ${minimum}
          config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${minimum}'
        end
      end
    end
`;

module.exports = function withIosDeploymentTarget(config, { minimum = '15.1' } = {}) {
  return withDangerousMod(config, [
    'ios',
    (config) => {
      const podfile = path.join(config.modRequest.platformProjectRoot, 'Podfile');
      const contents = fs.readFileSync(podfile, 'utf8');

      if (contents.includes(MARKER)) {
        return config;
      }

      // Append inside the existing post_install block, after the closing
      // paren of react_native_post_install(...).
      const anchor = /(post_install do \|installer\|[\s\S]*?\n {4}\)\n)/;
      if (!anchor.test(contents)) {
        throw new Error(
          'with-ios-deployment-target: could not find the post_install block in ios/Podfile. ' +
            'The Expo Podfile template changed; update this plugin.'
        );
      }

      fs.writeFileSync(
        podfile,
        contents.replace(anchor, `$1${buildPatch(minimum)}`),
        'utf8'
      );

      return config;
    },
  ]);
};
